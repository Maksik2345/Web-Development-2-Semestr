import { useRef, useState } from 'react';

export const Tooltip = ({ text }: { text: string }) => {
  const [position, setPosition] = useState(0);
  const tooltipRef = useRef(null);

  // Нужно измерить ширину подсказки и сдвинуть её,
  // чтобы не вылезала за край экрана
  // Какой хук использовать? Объясни выбор

  // Ответ: useLayoutEffect.
  // Чтобы узнать ширину подсказки, её сначала нужно отрисовать в DOM, а потом измерить
  // и при необходимости сдвинуть. Если сделать это в useEffect, браузер успеет показать
  // подсказку в старом положении (вылезающей за край), и только потом она «прыгнет»
  // на место — пользователь увидит мигание.
  // useLayoutEffect выполняется после расчёта DOM, но до того, как браузер покажет
  // кадр на экране. Измерение и сдвиг происходят «за кадром», и пользователь сразу
  // видит подсказку в правильном месте. Вычисления здесь лёгкие (одно измерение),
  // поэтому блокировка отрисовки не заметна.
  return <div ref={tooltipRef}>{text}</div>;
};
